"""Self-host the Inter webfonts so renders never race the Google Fonts CDN.

Downloads the latin + latin-ext woff2 subsets, drops them in video/public/fonts
and generates video/src/fonts.generated.ts (the @font-face CSS with staticFile()
URLs) for the Remotion build.

    python video/scripts/fetch_fonts.py
"""
from __future__ import annotations

import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
VIDEO = os.path.dirname(HERE)
PUBLIC = os.path.join(VIDEO, "public", "fonts")
GEN = os.path.join(VIDEO, "src", "fonts.generated.ts")

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36")
WANT = ("latin", "latin-ext")
FACES = [
    ("normal", 400), ("normal", 500), ("normal", 600),
    ("normal", 700), ("normal", 800),
    ("italic", 600), ("italic", 700),
]


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main() -> int:
    os.makedirs(PUBLIC, exist_ok=True)
    css_out = []
    for style, weight in FACES:
        if style == "normal":
            url = (f"https://fonts.googleapis.com/css2?family=Inter:wght@{weight}"
                   f"&display=swap")
        else:
            url = (f"https://fonts.googleapis.com/css2?family=Inter:ital,wght@1,{weight}"
                   f"&display=swap")
        css = get(url).decode("utf-8")
        blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css)
        for subset, block in blocks:
            if subset not in WANT:
                continue
            m = re.search(r"url\((https://[^)]+\.woff2)\)", block)
            if not m:
                continue
            name = f"inter-{weight}-{style}-{subset}.woff2"
            path = os.path.join(PUBLIC, name)
            if not os.path.exists(path):
                with open(path, "wb") as fh:
                    fh.write(get(m.group(1)))
            block = block.replace(m.group(1), "__URL__")
            block = re.sub(r"\s+", " ", block).strip()
            css_out.append(block.replace("__URL__", "PLACEHOLDER:" + name))
            print(f"  {name}")

    lines = [
        "// generated by video/scripts/fetch_fonts.py - do not edit",
        'import {staticFile} from "remotion";',
        "",
        "export const INTER_CSS = `",
    ]
    for block in css_out:
        fixed = re.sub(r"PLACEHOLDER:([\w.-]+)", r"' + staticFile('fonts/\1') + '", block)
        lines.append(fixed)
    lines.append("`;")
    os.makedirs(os.path.dirname(GEN), exist_ok=True)
    with open(GEN, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {GEN} ({len(css_out)} faces)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
